import express from 'express';
import cors from 'cors';
import cookieParser from 'cookie-parser';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import authRoutes from './routes/authRoutes.js';
import habitRoutes from './routes/habitRoutes.js';
const app=express();
app.disable('x-powered-by'); app.use(helmet());
app.use(cors({origin:process.env.CLIENT_URL||'http://localhost:5173',credentials:true}));
app.use(express.json({limit:'1mb'})); app.use(cookieParser());
app.get('/api/health',(_req,res)=>res.json({status:'ok',service:'AuraHabit API',timestamp:new Date().toISOString()}));
app.use('/api/auth',rateLimit({windowMs:15*60*1000,limit:100,standardHeaders:true,legacyHeaders:false}),authRoutes);
app.use('/api/habits',rateLimit({windowMs:15*60*1000,limit:300,standardHeaders:true,legacyHeaders:false}),habitRoutes);
app.use((_req,res)=>res.status(404).json({message:'API route not found.'}));
app.use((err,_req,res,_next)=>{console.error(err); if(err?.code===11000)return res.status(409).json({message:'An account with this email already exists.'}); if(err?.name==='ValidationError')return res.status(400).json({message:Object.values(err.errors).map(e=>e.message).join(', ')}); res.status(500).json({message:process.env.NODE_ENV==='production'?'Unexpected server error.':(err.message||'Unexpected server error.')});});
export default app;
